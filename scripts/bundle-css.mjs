import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Bundles the design system's stylesheets into a single dist/styles.css that
 * consumers import once: `import "inkwell/styles.css"`.
 *
 * Order matters: generated tokens first (they define the custom properties),
 * then the component/base styles that consume them.

 */
const root = resolve(process.cwd());
const inputs = [
  resolve(root, "src", "styles", "tokens.css"),
  resolve(root, "src", "styles", "inkwell.css"),
];
const outDir = resolve(root, "dist");
const outPath = resolve(outDir, "styles.css");

const header = "/* Inkwell design system — bundled styles. Generated by scripts/bundle-css.mjs. */\n";
const css = header + inputs.map((file) => readFileSync(file, "utf8")).join("\n");

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, css, "utf8");
console.log(`Bundled ${inputs.length} stylesheets → ${outPath}`);
